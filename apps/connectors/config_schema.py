"""The connector config format and its validation.

A connector config says how to turn AppConnect's canonical employee into the
object a third-party app expects. It is plain JSON, so it can be generated by an
LLM, reviewed in a pull request and applied at runtime without new code::

    {
      "app": "acme-payroll",
      "target": {"schema": "Worker", "operation": "POST /workers"},
      "fields": [
        {"source": "email", "target": "contact.work_email", "transform": "lowercase"},
        {"source": "status", "target": "active", "transform": "is_active"},
        {"constant": "AppConnect", "target": "source_system"}
      ],
      "unmapped": ["cost_center"]
    }

Validation happens in two passes: JSON Schema for shape, then semantic checks
against the third-party spec (targets exist, required targets covered, types fit).
"""

from jsonschema import Draft202012Validator

# Canonical employee fields available as `source` (see apps.employees.services.employee_payload).
CANONICAL_FIELDS: dict[str, str] = {
    "id": "string",
    "first_name": "string",
    "last_name": "string",
    "full_name": "string",
    "email": "string",
    "department": "string",
    "job_title": "string",
    "employment_type": "string",
    "status": "string",
    "hire_date": "date",
    "termination_date": "date",
    "manager_id": "string",
}

# transform name -> JSON type it produces
TRANSFORMS: dict[str, str] = {
    "none": "any",
    "lowercase": "string",
    "uppercase": "string",
    "iso_date": "string",
    "us_date": "string",
    "is_active": "boolean",
    "map": "any",
}

TARGET_PATH = r"^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$"

CONNECTOR_CONFIG_SCHEMA: dict = {
    "$schema": "https://json-schema.org/draft/2020-12/schema",
    "type": "object",
    "required": ["app", "target", "fields"],
    "additionalProperties": False,
    "properties": {
        "app": {"type": "string", "minLength": 1},
        "target": {
            "type": "object",
            "required": ["schema"],
            "additionalProperties": False,
            "properties": {"schema": {"type": "string"}, "operation": {"type": "string"}},
        },
        "fields": {
            "type": "array",
            "minItems": 1,
            "items": {
                "type": "object",
                "required": ["target"],
                "additionalProperties": False,
                "properties": {
                    "source": {"enum": list(CANONICAL_FIELDS)},
                    "constant": {"type": ["string", "number", "boolean"]},
                    "target": {"type": "string", "pattern": TARGET_PATH},
                    "transform": {"enum": list(TRANSFORMS)},
                    "values": {
                        "type": "object",
                        "additionalProperties": {"type": ["string", "number", "boolean"]},
                    },
                    "confidence": {"type": "number", "minimum": 0, "maximum": 1},
                },
                "oneOf": [{"required": ["source"]}, {"required": ["constant"]}],
            },
        },
        "unmapped": {"type": "array", "items": {"type": "string"}},
    },
}

_validator = Draft202012Validator(CONNECTOR_CONFIG_SCHEMA)

# JSON types each transform output can satisfy.
_COMPATIBLE = {
    "string": {"string"},
    "date": {"string"},
    "boolean": {"boolean"},
    "any": {"string", "boolean", "number", "integer"},
}


def _output_type(field: dict) -> str:
    if "constant" in field:
        value = field["constant"]
        return "boolean" if isinstance(value, bool) else "number" if isinstance(value, int | float) else "string"
    transform = field.get("transform", "none")
    if transform in ("none", "map"):
        return "any" if transform == "map" else CANONICAL_FIELDS[field["source"]]
    return TRANSFORMS[transform]


def validate_config(config: dict, target_fields: dict[str, dict] | None = None) -> list[str]:
    """Return a list of human-readable problems; empty means valid.

    ``target_fields`` is the flattened third-party schema from
    :func:`apps.connectors.spec_parser.flatten_schema`; when given, targets are
    checked against it.
    """
    errors = [
        f"{'/'.join(map(str, e.absolute_path)) or '<root>'}: {e.message}"
        for e in sorted(_validator.iter_errors(config), key=lambda e: list(e.absolute_path))
    ]
    if errors:
        return errors

    seen: set[str] = set()
    for i, field in enumerate(config["fields"]):
        target = field["target"]
        if target in seen:
            errors.append(f"fields/{i}: target '{target}' is mapped more than once")
        seen.add(target)
        if field.get("transform") == "map" and not field.get("values"):
            errors.append(f"fields/{i}: transform 'map' needs a non-empty 'values' table")

        if target_fields is None:
            continue
        spec = target_fields.get(target)
        if spec is None:
            errors.append(f"fields/{i}: target '{target}' does not exist in {config['target']['schema']}")
            continue
        produced = _output_type(field)
        expected = spec.get("type", "string")
        compatible = _COMPATIBLE.get(produced, {produced}) | ({"integer"} if produced == "number" else set())
        if produced != "any" and expected not in compatible:
            errors.append(f"fields/{i}: '{target}' expects {expected} but mapping produces {produced}")
        enum = spec.get("enum")
        if enum and field.get("transform") != "map" and "constant" not in field:
            errors.append(f"fields/{i}: '{target}' is an enum {enum}; use transform 'map' with a values table")

    if target_fields is not None:
        missing = sorted(t for t, s in target_fields.items() if s.get("required") and t not in seen)
        if missing:
            errors.append(f"required target fields not mapped: {', '.join(missing)}")
    return errors
